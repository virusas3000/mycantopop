def main():
    # Load existing slugs
    existing = set()
    for fn in os.listdir(ARTICLES_DIR):
        if fn.endswith('.html') and fn != 'index.html':
            existing.add(fn.replace('.html', ''))
    
    # Generate articles
    created = []
    for slug, title, desc, tag, card_desc in ARTICLES:
        if slug in existing:
            print(f"SKIP (exists): {slug}")
            continue
        sections_data = SECTIONS.get(slug, [])
        if not sections_data:
            print(f"SKIP (no content): {slug}")
            continue
        html = make_article_html(slug, title, desc, sections_data)
        path = os.path.join(ARTICLES_DIR, slug + ".html")
        with open(path, 'w', encoding='utf-8') as f:
            f.write(html)
        created.append((slug, title, desc, tag, card_desc))
        print(f"CREATED: {slug}")
    
    print(f"\nTotal created: {len(created)}")
    
    # Update index.html — insert cards before closing </div> of grid
    index_path = os.path.join(ARTICLES_DIR, "index.html")
    with open(index_path, 'r', encoding='utf-8') as f:
        index_html = f.read()
    
    cards_html = ""
    for slug, title, desc, tag, card_desc in created:
        cards_html += f'      <a class="card" href="/articles/{slug}.html">\n'
        cards_html += f'        <span class="card-date">{TODAY}</span>\n'
        cards_html += f'        <span class="card-tag">{tag}</span>\n'
        cards_html += f'        <h2>{_html.escape(title)}</h2>\n'
        cards_html += f'        <p>{_html.escape(card_desc)}</p>\n'
        cards_html += f'        <span class="card-arrow">→</span>\n'
        cards_html += f'      </a>\n'
    
    # Insert before the last </div> that closes the grid
    # The grid ends with: </div>\n\n  <footer>
    grid_close = '</div>\n\n  <footer>'
    if grid_close in index_html:
        index_html = index_html.replace(grid_close, cards_html + grid_close, 1)
    else:
        # fallback: find last </div> before footer
        idx = index_html.rfind('</div>')
        index_html = index_html[:idx] + cards_html + index_html[idx:]
    
    with open(index_path, 'w', encoding='utf-8') as f:
        f.write(index_html)
    print("Updated index.html")
    
    # Update sitemap.xml
    sitemap_path = os.path.join(BASE, "sitemap.xml")
    with open(sitemap_path, 'r', encoding='utf-8') as f:
        sitemap = f.read()
    
    sitemap_entries = ""
    for slug, *_ in created:
        sitemap_entries += f"  <url>\n    <loc>https://mycantopop.hk/articles/{slug}.html</loc>\n    <lastmod>{DATE_COMPACT}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.7</priority>\n  </url>\n"
    
    # Insert before </urlset>
    sitemap = sitemap.replace('</urlset>', sitemap_entries + '</urlset>', 1)
    with open(sitemap_path, 'w', encoding='utf-8') as f:
        f.write(sitemap)
    print("Updated sitemap.xml")
    
    print("\nDone! Ready for git commit.")

if __name__ == '__main__':
    main()